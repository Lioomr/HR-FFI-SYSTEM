def translated(key, language=None):
    catalog = AR if (language or get_language() or "en").lower().startswith("ar") else EN
    return catalog[key]


def enum_directory(language=None):
    return {
        name: [{**entry, "label": translated(entry["label_key"], language)} for entry in entries]
        for name, entries in ENUMS.items()
    }
