def monetary_amount(profile, level):
    basis = level.get("amount_basis")
    value = Decimal(level["amount_value"]) if level.get("amount_value") else Decimal("0")
    daily = (profile.total_salary or Decimal("0")) / Decimal("30")
    if basis == "daily_wage_percent":
        return (daily * value / Decimal("100")).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
    if basis == "daily_wage_days":
        return (daily * value).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
    return Decimal("0.00")
