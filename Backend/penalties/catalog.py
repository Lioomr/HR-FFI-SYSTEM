from decimal import ROUND_HALF_UP, Decimal


def _level(value):
    if value == "W":
        return {"action": "written_warning", "amount_basis": None, "amount_value": None}
    if value.startswith("P"):
        return {"action": "deduction", "amount_basis": "daily_wage_percent", "amount_value": value[1:]}
    if value.startswith("D"):
        return {"action": "deduction", "amount_basis": "daily_wage_days", "amount_value": value[1:]}
    return {"action": value, "amount_basis": None, "amount_value": None}


def _entry(section, row, page, en, ar, values, *, period=None, extra="", automatic=False):
    return {
        "code": f"{section}{row:02d}",
        "category": {"W": "work_time", "O": "work_organization", "B": "worker_conduct"}[section],
        "recurrence_group": f"{section}{row:02d}",
        "title_en": en,
        "title_ar": ar,
        "description_en": en,
        "description_ar": ar,
        "count_period": period
        or ("monthly" if section == "W" and row <= 10 else "contract_year" if section == "W" else "cumulative"),
        "levels": [{"occurrence": n, **_level(value)} for n, value in enumerate(values, 1) if value],
        "source_page": page,
        "source_row": row,
        "automatic": automatic,
        "extra_wage_deduction": extra,
    }


